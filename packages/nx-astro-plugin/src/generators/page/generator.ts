import type { Tree } from '@nx/devkit';
import {
  formatFiles,
  joinPathFragments,
  readProjectConfiguration,
} from '@nx/devkit';
import { relative } from 'node:path';
import { parseAstroConfigDirs } from '../../utils/astro';
import { toKebab, toPascal } from '../../utils/naming';

interface Schema {
  project: string;
  name: string;
  directory?: string;
  type?: 'static' | 'dynamic';
  layout?: string;
}

function getLayoutDetails(
  projectRoot: string,
  srcDir: string,
  pageDirectory: string,
  layout: string | undefined,
) {
  if (!layout) return undefined;

  const layoutParts = layout.replace(/\\/g, '/').split('/');
  const layoutName = layoutParts.pop() ?? layout;
  const componentName = toPascal(layoutName);
  const layoutFileName = `${componentName}.astro`;
  const layoutDirectory = joinPathFragments(
    projectRoot,
    srcDir,
    'layouts',
    ...layoutParts,
  );
  const importDirectory = relative(pageDirectory, layoutDirectory).replace(
    /\\/g,
    '/',
  );
  const importPrefix = importDirectory.startsWith('.')
    ? importDirectory
    : `./${importDirectory}`;

  return {
    componentName,
    importPath: `${importPrefix}/${layoutFileName}`,
  };
}

function generateStaticPage(
  name: string,
  layoutDetails: ReturnType<typeof getLayoutDetails>,
): string {
  const title = JSON.stringify(name);
  const description = JSON.stringify(`${name} page description`);
  const layoutImport = layoutDetails
    ? `import ${layoutDetails.componentName} from '${layoutDetails.importPath}';\n`
    : '';
  const layoutWrapper = layoutDetails
    ? `<${layoutDetails.componentName} title={title} description={description}>\n  `
    : '';
  const layoutClose = layoutDetails
    ? `\n</${layoutDetails.componentName}>`
    : '';
  const indent = layoutDetails ? '  ' : '';

  return `---
// Generated by @forastro/nx-astro-plugin:page (static)
${layoutImport}const title = ${title};
const description = ${description};
---

${layoutWrapper}${indent}<div>
${indent}  <h1>{title}</h1>
${indent}  <!-- TODO: Add your page content here -->
${indent}</div>${layoutClose}
`;
}

function generateDynamicPage(
  name: string,
  layoutDetails: ReturnType<typeof getLayoutDetails>,
): string {
  const paramName =
    toKebab(name).replace(/^[^a-z]+|[^a-z0-9_]/gi, '') || 'slug';
  const layoutImport = layoutDetails
    ? `import ${layoutDetails.componentName} from '${layoutDetails.importPath}';\n`
    : '';
  const layoutWrapper = layoutDetails
    ? `<${layoutDetails.componentName}\n  title={entry.data.title}\n  description={entry.data.description}\n>\n  `
    : '';
  const layoutClose = layoutDetails
    ? `\n</${layoutDetails.componentName}>`
    : '';
  const indent = layoutDetails ? '  ' : '';

  return `---
// Generated by @forastro/nx-astro-plugin:page (dynamic)
${layoutImport}import { getCollection, render } from 'astro:content';

export async function getStaticPaths() {
  // TODO: Change 'posts' to your target collection name
  const entries = await getCollection('posts');
  return entries.map((entry) => ({
    params: { ${paramName}: entry.id },
    props: { entry },
  }));
}

const { entry } = Astro.props;
const { Content } = await render(entry);
---

${layoutWrapper}${indent}<article>
${indent}  <header>
${indent}    <h1>{entry.data.title}</h1>
${indent}    {entry.data.description && (
${indent}      <p class="description">{entry.data.description}</p>
${indent}    )}
${indent}  </header>
${indent}  <Content />
${indent}</article>${layoutClose}
`;
}

/** Generates an Astro page in the project's configured pages directory. */
export default async function generator(tree: Tree, options: Schema) {
  const project = readProjectConfiguration(tree, options.project);
  const pageType = options.type ?? 'static';
  const { srcDir, pagesDir } = parseAstroConfigDirs(project.root);
  const baseDirectory = options.directory?.replace(/\\\\/g, '/') ?? '';
  const targetDirectory = joinPathFragments(
    project.root,
    pagesDir,
    baseDirectory,
  );
  const pageName = toKebab(options.name);
  const routeName =
    pageType === 'dynamic' && !pageName.startsWith('[')
      ? `[${pageName}]`
      : pageName;
  const filePath = joinPathFragments(targetDirectory, `${routeName}.astro`);
  const layoutDetails = getLayoutDetails(
    project.root,
    srcDir,
    targetDirectory,
    options.layout,
  );

  if (!tree.exists(filePath)) {
    const contents =
      pageType === 'dynamic'
        ? generateDynamicPage(options.name, layoutDetails)
        : generateStaticPage(options.name, layoutDetails);
    tree.write(filePath, contents);
  }

  await formatFiles(tree);
}
